    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:K{len(articles)+1}"

    for r, art in enumerate(articles, 2):
        values = [
            r - 1,
            art["lookup"],
            art["name"],
            art["bab"],
            art["fasl"],
            art["keywords"],
            art["text"],
            art["explain"],
            art["apply"],
            art["amend"] or "لا تعديل لاحق على نص هذه الطبعة.",
            "نعم" if art["amend"] else "",
        ]
        for c, v in enumerate(values, 1):
            cell = ws.cell(r, c, v)
            cell.font = font(11)
            cell.alignment = align(True, "right", "top")
            if r % 2 == 0 and c <= 6:
                cell.fill = fill(ROW_ALT)
            if c == 10 and art["amend"]:
                cell.fill = fill(SAND)
                cell.font = font(10, False, RED)
            if c == 11 and art["amend"]:
                cell.fill = fill(GOLD)
                cell.font = font(11, True, WHITE)
                cell.alignment = align(True, "center", "center")
        ws.row_dimensions[r].height = 48

