def validate(articles: list[dict]) -> None:
    by = {a["key"]: a for a in articles}
    assert len(articles) == 177, len(articles)
    assert "يوليو" in by["1"]["text"] and "أبريل" not in by["1"]["text"].split("7- سعر")[0]
    assert "لا تقل عن معدل التضخم" not in by["35"]["text"]
    assert "رئيس مجلس إدارة الهيئة" in by["35"]["text"]
    assert "(5.7%)" in by["111"]["text"] and "(6%)" not in by["111"]["text"]
    assert "ثلاثين" in by["112"]["text"] and "خمسة عشر" not in by["112"]["text"]
    assert "160.5" in by["111"]["text"]
    assert by["2"]["text"].startswith("تسري أحكام هذا القانون")
    assert "تسري أحكام هذا القانون على الفئات" not in by["1"]["text"]
    assert by["3"]["text"].startswith("يشمل نظام التأمينات الاجتماعية")
    assert "يشمل نظام التأمينات" not in by["2"]["text"]
    assert "تأمين البطالة" in by["3"]["text"]
    assert by["14"]["text"].startswith("ينشأ صندوق لإدارة واستثمار")
    assert "ينشأ صندوق" not in by["13"]["text"]
    assert "سوء سلوك" in by["57"]["text"]
    assert "لا يستحق تعويض الأجر" not in by["56"]["text"]
    assert by["103"]["text"].startswith("يوقف صرف معاش المستحق")
    assert "يوقف صرف معاش المستحق" not in by["102"]["text"]
    assert "حصة يلتزم بها صاحب العمل بواقع (1%)" in by["36"]["text"]
    assert "رئيس الجمهورية" not in by["35"]["text"]
    assert "العاجز عن الكسب" in by["1"]["text"]
    assert "(75%)" in by["76"]["text"] and "(85%)" in by["76"]["text"]
    assert "عشرة أشهر" in by["77"]["text"]
    assert "(40%)" in by["90"]["text"]
    for a in articles:
        tail = [ln.strip() for ln in a["text"].splitlines() if ln.strip()][-1]
        assert not re.fullmatch(r"الباب\s+\S.*", tail), (a["key"], tail)
        assert not tail.startswith("(الفصل"), (a["key"], tail)
        assert tail not in HEADING_LINES, (a["key"], tail)
    assert by["35"]["text"].rstrip().endswith("أو وفاته.")
    assert by["4"]["text"].rstrip().endswith("لأي سبب من الأسباب.")
    assert by["163"]["text"].rstrip().endswith("ضوابط تنفيذ هذه المادة.")
    assert "خمسمائة جنيه" in by["105"]["text"]
    names = [a["name"] for a in articles]
    assert len(names) == len(set(names)), "duplicate short names"
    lookups = [a["lookup"] for a in articles]
    assert len(lookups) == len(set(lookups))
    for a in articles:
        assert a["text"] and len(a["text"]) < 32000, a["key"]
        assert a["explain"] and a["apply"] and a["name"]
    # issuance date line should not have swallowed article 7
    assert "1/1/2020" in by["ص7"]["text"]
    print("validation ok", len(articles), "articles")
    print("art1 inflation:", [ln for ln in by["1"]["text"].splitlines() if ln.startswith("6-")][0][:180])
    print("art35:", by["35"]["text"].splitlines()[0][:160])
    print("art112:", by["112"]["text"][:180])
    longest = max(articles, key=lambda a: len(a["text"]))
    print("longest", longest["key"], len(longest["text"]))


