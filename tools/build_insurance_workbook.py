    wb.defined_names.add(DefinedName(name="ArticleNumbers", attr_text=f"'فهرس المواد'!$B$2:$B${last}"))
    wb.defined_names.add(DefinedName(name="ArticleNames", attr_text=f"'فهرس المواد'!$C$2:$C${last}"))
    return ws


