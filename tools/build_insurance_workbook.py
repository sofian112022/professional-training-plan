def strip_trailing_headings(text: str) -> str:
    """Drop chapter titles that the source page left stuck to the previous article."""
    lines = text.splitlines()
    removed = 0
    while lines and removed < 8:
        s = lines[-1].strip()
        if not s:
            lines.pop()
            continue
        if (
            re.fullmatch(r"الباب\s+\S.*", s)
            or re.fullmatch(r"\(الفصل\s+.+\)", s)
            or s in HEADING_LINES
        ):
            lines.pop()
            removed += 1
            continue
        break
    return "\n".join(lines).strip()


def explain(art: dict) -> tuple[str, str]:
    key = art["key"]
    text = art["text"]
    focus = FOCUS.get(key) or FOCUS.get(art["num"])
    if not focus:
        first = text.split("\n")[0].strip()
        focus = "الحكم المباشر: " + first[:420]
    bab = art["bab"]
    play = PLAYBOOK.get(bab, PLAYBOOK["الباب العاشر"])
    figures = extract_figures(text)
    fig_line = ""
    if figures:
        fig_line = "أرقام ومواعيد ظاهرة في النص: " + "؛ ".join(figures[:8]) + "."
    explanation = focus
    if fig_line:
        explanation += "\n\n" + fig_line
    explanation += (
        "\n\nهذا الشرح أداة عمل للموارد البشرية والحسابات، وليس فتوى. "
        "عند التنفيذ يُراجع نص المادة أعلاه، ثم اللائحة التنفيذية الصادرة بقرار رئيس مجلس الوزراء رقم 2437 لسنة 2021، "
        "ثم النماذج والمنشورات السارية على موقع الهيئة القومية للتأمين الاجتماعي."
    )
    return explanation, play


def extract_figures(text: str) -> list[str]:
    found = []
    for m in re.finditer(r"\([^()\n]{0,30}\d[^()\n]{0,20}%[^()\n]{0,10}\)", text):
        s = re.sub(r"\s+", " ", m.group(0)).strip()
        if s not in found:
            found.append(s)
    for m in re.finditer(r"\b\d+(?:\.\d+)?%", text):
        if m.group(0) not in found:
            found.append(m.group(0))
    for pat in (
        r"خلال خمسة عشر يوما",
        r"أول الشهر التالي",
        r"أربعة أسابيع",
        r"ثلاثين يوما",
        r"ثلاثين يومًا",
        r"ستة أشهر",
        r"سبع سنوات",
    ):
        if re.search(pat, text) and pat not in found:
            found.append(pat.replace("\\s+", " "))
    return found


