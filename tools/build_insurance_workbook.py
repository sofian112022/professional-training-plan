def clean(text: str) -> str:
    text = text.translate(WEST)
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def load_articles() -> list[dict]:
    raw = BLOG.read_text(encoding="utf-8")
    start = raw.find("(المادة الأولى)")
    end = raw.find("\n(1) استبدل")
    raw = raw[start:end]
    cut = raw.find("\nالباب الأول\n")
    head, body = raw[:cut], raw[cut:]

    ordinals = [
        ("الأولى", "ص1"),
        ("الثانية", "ص2"),
        ("الثالثة", "ص3"),
        ("الرابعة", "ص4"),
        ("الخامسة", "ص5"),
        ("السادسة", "ص6"),
        ("السابعة", "ص7"),
    ]
    articles: list[dict] = []
    for label, key in ordinals:
        m = re.search(
            rf"\(المادة {label}\)\n+(.*?)(?=\n\(المادة |\nيبصم |\nقانون التأمينات)",
            head,
            re.S,
        )
        if not m:
            raise SystemExit(f"missing issuance {label}")
        articles.append(
            {
                "key": key,
                "num": None,
                "sort": int(key[1:]),
                "kind": "إصدار",
                "label": f"مادة الإصدار {label}",
                "lookup": f"إصدار-{label}",
                "text": clean(m.group(1)),
            }
        )

    parts = re.split(r"\nمادة \((\d+)\):\n", body)
    found: dict[int, str] = {}
    for i in range(1, len(parts), 2):
        found[int(parts[i])] = parts[i + 1]
    # Five headings were dropped in the source page, so each body was glued
    # to the previous article. Split them back on their opening sentence.
    carve(found, 1, 2, "تسري أحكام هذا القانون على الفئات الآتية:")
    carve(found, 2, 3, "يشمل نظام التأمينات الاجتماعية التأمينات الآتية:")
    carve(found, 13, 14, "ينشأ صندوق لإدارة واستثمار")
    carve(found, 56, 57, "لا يستحق تعويض الأجر وتعويض الإصابة")
    carve(found, 102, 103, "يوقف صرف معاش المستحق")
    missing = [n for n in range(1, 171) if n not in found or not found[n].strip()]
    if missing:
        raise SystemExit(f"still missing articles: {missing}")

    for n in range(1, 171):
        text = clean(found[n])
        text = patch(n, text)
        bab, fasl = chapter_of(n)
        articles.append(
            {
                "key": str(n),
                "num": n,
                "sort": 100 + n,
                "kind": "قانون",
                "label": f"مادة {n}",
                "lookup": f"مادة {n}",
                "text": text,
                "bab": bab,
                "fasl": fasl,
            }
        )
    for art in articles:
        if art["kind"] == "إصدار":
            art["bab"] = "مواد الإصدار"
            art["fasl"] = "قانون رقم 148 لسنة 2019"
        name_key = art["num"] if art["num"] is not None else art["key"]
        art["name"] = NAMES[name_key]
        art["keywords"] = KEYWORDS.get(art["num"], art["name"]) if art["num"] else art["name"]
        art["amend"] = AMENDMENTS.get(art["num"], "")
        art["explain"], art["apply"] = explain(art)
    return articles


def carve(found: dict[int, str], host: int, new: int, marker: str) -> None:
    body = found[host]
    idx = body.find(marker)
    if idx < 0:
        raise SystemExit(f"could not split article {new} out of article {host}")
    found[host] = body[:idx].strip()
    found[new] = body[idx:].strip()


def chapter_of(n: int) -> tuple[str, str]:
    for a, b, bab, fasl in CHAPTERS:
        if a <= n <= b:
            return bab, fasl
    raise SystemExit(f"no chapter for {n}")


