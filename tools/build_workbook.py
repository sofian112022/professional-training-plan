def merge(ws, row, start, end, value, fnt, fill, align, height=None, border=None):
    ws.merge_cells(start_row=row, start_column=start, end_row=row, end_column=end)
    cell = ws.cell(row, start)
    paint(cell, value, fnt, fill, align, border)
    for col in range(start, end + 1):
        ws.cell(row, col).fill = fill
        ws.cell(row, col).alignment = align
        if border:
            ws.cell(row, col).border = border
    if height:
        ws.row_dimensions[row].height = height
    return cell


def split_vis(text: str, limit: int = 500) -> list[str]:
    parts: list[str] = []
    buf = ""
    for para in text.split("\n"):
        if buf and len(buf) + len(para) + 1 <= limit:
            buf = buf + "\n" + para
        else:
            if buf:
                parts.append(buf)
            while len(para) > limit:
                cut = para.rfind(" ", 0, limit)
                if cut < 240:
                    cut = limit
                parts.append(para[:cut].strip())
                para = para[cut:].strip()
            buf = para
    if buf:
        parts.append(buf)
    return parts or [""]


def row_height(text: str, cpl: int = 52) -> float:
    lines = 0
    for para in text.split("\n"):
        lines += max(1, (len(para) + cpl - 1) // cpl)
    return min(200, max(30, 14 + lines * 18))


