def write_structure(ws, arts: list[dict]):
    apply_rtl(ws, grid=False)
    ws.sheet_properties.tabColor = TEAL
    for col, width in enumerate([28, 46, 55, 18, 18], 1):
        ws.column_dimensions[get_column_letter(col)].width = width
    merge(ws, 1, 1, 5, "هيكل القانون", font(18, True, WHITE), FILL(NAVY), RTL, 30)
    for col, header in enumerate(["الكتاب", "الباب", "الفصل", "من مادة", "إلى مادة"], 1):
        paint(ws.cell(2, col), header, font(11, True, WHITE), FILL(TEAL), RTL)
    groups = []
    for art in arts:
        if art["kind"] != "law":
            continue
        key = (art["book"], art["bab"], art["fasl"])
        if not groups or groups[-1][0] != key:
            groups.append([key, art["num"], art["num"]])
        else:
            groups[-1][2] = art["num"]
    for i, (key, start, end) in enumerate(groups):
        row = 3 + i
        vals = [key[0], key[1], key[2], f"مادة {ar(start)}", f"مادة {ar(end)}"]
        for col, value in enumerate(vals, 1):
            paint(ws.cell(row, col), value, font(11), FILL(PAPER if i % 2 == 0 else CREAM), RTL)
        ws.row_dimensions[row].height = 32
    ws.freeze_panes = "A3"
    ws.auto_filter.ref = f"A2:E{2+len(groups)}"
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToWidth = 1
    ws.print_title_rows = "1:2"


