def penalty_index(arts: list[dict]) -> dict[tuple[str, int], list[dict]]:
    index: dict[tuple[str, int], list[dict]] = defaultdict(list)
    for art in arts:
        if art["kind"] != "law" or not (281 <= art["num"] <= 297):
            continue
        text_w = western(art["text"])
        if "المادة السابعة من مواد إصدار" in art["text"] or "المادة السابعة من مواد الاصدار" in fold(art["text"]):
            index[("issue", 7)].append(art)
        for match in re.finditer(r"(المادتين|المواد|المادة)(.{0,2200}?)من هذا القانون", text_w):
            segment = match.group(0)
            if any(x in segment for x in ("قانون المرافعات", "قانون الطفل", "قانون التأمين", "قانون الشركات")):
                continue
            # «٨٢/البندين ١ و٢» تحيل إلى المادة ٨٢ فقط، لا إلى المادتين ١ و٢.
            segment = re.sub(r"/[^،,)\n]*", " ", segment)
            for n in re.findall(r"\d+", segment):
                num = int(n)
                if 1 <= num <= 298 and num != art["num"]:
                    index[("law", num)].append(art)
    return index


def penalty_sentence(art: dict, linked: list[dict]) -> str:
    if not linked:
        if art["kind"] == "law" and 280 <= art["num"] <= 298:
            return "هذه مادة من باب العقوبات. تُقرأ مع المواد التي تحيل إليها، وتُدرج الغرامة في سجل مخاطر الامتثال."
        return ""
    bits = []
