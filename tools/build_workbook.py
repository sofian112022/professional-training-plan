def line_items(text: str) -> tuple[list[str], list[str]]:
    prose: list[str] = []
    items: list[str] = []
    for ln in [x.strip() for x in text.splitlines() if x.strip()]:
        w = western(ln)
        numbered = re.match(r"^\(?\s*\d+\s*[-–—.)]", w) or re.match(r"^\(\s*[أ-ي]\s*\)", ln)
        if numbered:
            items.append(re.sub(r"\s+", " ", ln))
        else:
            prose.append(re.sub(r"\s+", " ", ln))
    return prose, items


